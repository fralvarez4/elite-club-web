import { test, expect } from '@playwright/test'

test('hover categories and gender sections filter the inventory', async ({ page }) => {
  await page.goto('/')
  const products = page.getByRole('button', { name: 'Hombre', exact: true })
  await products.hover()
  await expect(products).toHaveAttribute('aria-expanded', 'true')
  await page.locator('#menu-Hombre').getByRole('link', { name: 'Hoodies' }).click()
  await expect(page.locator('.section-heading')).toContainText('Hoodies')
  await expect(page.getByRole('button', { name: 'Ver Nocta Cap', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Mujer', exact: true }).hover()
  await page.locator('#menu-Mujer').getByRole('link', { name: 'Ver todo' }).click()
  await expect(page.locator('.product-card')).toHaveCount(1)
  await expect(page.locator('.product-title')).toHaveText('Corteiz Womens Classic Tank Top')
  await expect(page.getByRole('button', { name: 'Mujer', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.locator('.filter-panel > summary').click()
  await page.locator('.filter-panel').getByRole('button', { name: 'Limpiar filtros', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Mujer', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Hombre', exact: true }).hover()
  await page.locator('#menu-Hombre').getByRole('link', { name: 'Ver todo' }).click()
  await expect(page.locator('.results')).toContainText('42 productos')
  await expect(page.locator('.catalog-tabs')).toHaveCount(0)
})

test('navigation works with keyboard and touch and closes on dismissal', async ({ page }) => {
  await page.goto('/')
  const products = page.getByRole('button', { name: 'Hombre', exact: true })
  await expect(products).toBeEnabled()
  await products.focus()
  await expect(products).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Escape')
  await expect(products).toBeFocused()
  await expect(products).toHaveAttribute('aria-expanded', 'false')
  await page.setViewportSize({ width: 390, height: 844 })
  await products.hover()
  await page.locator('#menu-Hombre').getByRole('link', { name: 'Accesorios' }).click()
  await expect(page.locator('.section-heading')).toContainText('Accesorios')
  await expect(products).toHaveAttribute('aria-expanded', 'false')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('single-page departments, search and logo preserve the cart', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.home-categories')).toHaveCount(0)
  await expect(page.locator('.product-card')).toHaveCount(12)
  await page.getByRole('button', { name: 'Hombre', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  await expect(page.locator('.campaign')).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Hombre', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.locator('.quick-add').first().click()
  await page.getByRole('link', { name: 'Elite Club, inicio', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByRole('button', { name: 'Carrito 1', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Buscar productos', exact: true }).click()
  await page.getByPlaceholder('Buscá tu próxima pieza').fill('Corteiz Cap')
  await page.getByRole('button', { name: 'Enviar búsqueda' }).click()
  await expect(page).toHaveURL(/\/$/)
  await expect(page.locator('.product-card')).toHaveCount(1)
  await page.getByRole('link', { name: 'Volver al inicio', exact: true }).click()
  await expect(page.locator('.campaign')).toBeVisible()
  await page.getByRole('button', { name: 'Mujer', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByRole('button', { name: 'Mujer', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.product-card')).toHaveCount(1)
})
